-- V4: seat locks, bookings, and lock/booking ownership on the show inventory

CREATE TABLE seat_locks (
    id          UUID        PRIMARY KEY,           -- generated by the app before Redis + DB, so both use one id
    user_id     BIGINT      NOT NULL REFERENCES users (id),
    show_id     BIGINT      NOT NULL REFERENCES shows (id),
    seat_count  INT         NOT NULL,
    status      VARCHAR(10) NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    closed_at   TIMESTAMPTZ,
    CONSTRAINT ck_seat_locks_status     CHECK (status IN ('ACTIVE', 'RELEASED', 'EXPIRED', 'CONSUMED')),
    CONSTRAINT ck_seat_locks_seat_count CHECK (seat_count BETWEEN 1 AND 10),
    CONSTRAINT ck_seat_locks_closed     CHECK ((status = 'ACTIVE') = (closed_at IS NULL))
);
-- Anti-hoarding: one live lock per user per show.
CREATE UNIQUE INDEX uk_seat_locks_one_active ON seat_locks (user_id, show_id) WHERE status = 'ACTIVE';
-- Sweeper: "ACTIVE locks past expiry", oldest first. Partial index stays small (only live locks).
CREATE INDEX idx_seat_locks_active_expiry ON seat_locks (expires_at) WHERE status = 'ACTIVE';

CREATE TABLE bookings (
    id                 BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    booking_reference  VARCHAR(12) NOT NULL,
    user_id            BIGINT      NOT NULL REFERENCES users (id),
    show_id            BIGINT      NOT NULL REFERENCES shows (id),
    seat_lock_id       UUID        NOT NULL REFERENCES seat_locks (id),
    status             VARCHAR(20) NOT NULL,
    total_amount_paise BIGINT      NOT NULL,
    currency           VARCHAR(3)  NOT NULL DEFAULT 'INR',
    expires_at         TIMESTAMPTZ NOT NULL,
    confirmed_at       TIMESTAMPTZ,
    closed_at          TIMESTAMPTZ,
    version            BIGINT      NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL,
    updated_at         TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_bookings_reference UNIQUE (booking_reference),
    -- One lock becomes at most one booking: makes POST /bookings idempotent per lock.
    CONSTRAINT uk_bookings_seat_lock UNIQUE (seat_lock_id),
    CONSTRAINT ck_bookings_amount    CHECK (total_amount_paise > 0),
    CONSTRAINT ck_bookings_status    CHECK (status IN ('PENDING', 'PAYMENT_PENDING', 'CONFIRMED', 'PAYMENT_FAILED',
                                                       'EXPIRED', 'CANCELLED', 'REFUND_PENDING', 'REFUNDED'))
);
CREATE INDEX idx_bookings_user_created ON bookings (user_id, created_at DESC, id DESC);
CREATE INDEX idx_bookings_open_expiry  ON bookings (expires_at) WHERE status IN ('PENDING', 'PAYMENT_PENDING');

-- Immutable record of what was bought, with label/type/price snapshotted at booking time.
CREATE TABLE booking_seats (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    booking_id   BIGINT      NOT NULL REFERENCES bookings (id),
    show_seat_id BIGINT      NOT NULL REFERENCES show_seats (id),
    seat_label   VARCHAR(6)  NOT NULL,
    seat_type    VARCHAR(10) NOT NULL,
    price_paise  BIGINT      NOT NULL,
    confirmed    BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_booking_seats_booking_seat UNIQUE (booking_id, show_seat_id),
    CONSTRAINT ck_booking_seats_price        CHECK (price_paise > 0)
);
-- Defense in depth: even if application code were wrong, two CONFIRMED bookings can't hold one show seat.
CREATE UNIQUE INDEX uk_booking_seats_confirmed_once ON booking_seats (show_seat_id) WHERE confirmed;

ALTER TABLE show_seats
    ADD COLUMN lock_id      UUID REFERENCES seat_locks (id),
    ADD COLUMN locked_until TIMESTAMPTZ,
    ADD COLUMN booking_id   BIGINT REFERENCES bookings (id),
    -- status and ownership columns can never disagree:
    ADD CONSTRAINT ck_show_seats_locked CHECK ((status = 'LOCKED') = (lock_id IS NOT NULL)
                                                AND (lock_id IS NULL) = (locked_until IS NULL)),
    ADD CONSTRAINT ck_show_seats_booked CHECK ((status = 'BOOKED') = (booking_id IS NOT NULL));

CREATE INDEX idx_show_seats_lock ON show_seats (lock_id) WHERE lock_id IS NOT NULL;
